"""Build a relative-scope PWA from the exact distributed files; no extra packages."""
from pathlib import Path
import hashlib
import json
import math
import re
import struct
import zlib


def _icon(size):
    """Rasterize the existing geometric school mark with simple supersampling."""
    lines = [(17, 40, 17, 24), (17, 24, 33, 24),
             (47, 24, 47, 40), (47, 40, 31, 40), (23, 45, 41, 19)]
    background, foreground = (36, 63, 53), (232, 246, 200)

    def distance(x, y, line):
        ax, ay, bx, by = line
        dx, dy = bx - ax, by - ay
        t = max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
        return math.hypot(x - ax - t * dx, y - ay - t * dy)

    data = bytearray()
    for y in range(size):
        data.append(0)
        for x in range(size):
            coverage = sum(min(distance((x + sx) * 64 / size, (y + sy) * 64 / size, line)
                               for line in lines) <= 2
                           for sx, sy in [(0.25, 0.25), (0.75, 0.25), (0.25, 0.75), (0.75, 0.75)]) / 4
            data.extend(round(a + (b - a) * coverage) for a, b in zip(background, foreground))

    def chunk(kind, contents):
        return struct.pack('!I', len(contents)) + kind + contents + struct.pack('!I', zlib.crc32(kind + contents))

    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('!2I5B', size, size, 8, 2, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(data, 9)) + chunk(b'IEND', b''))


def build_pwa(root, html, asset_manifest):
    root = Path(root)
    icon_dir = root / 'icons'
    icon_dir.mkdir(exist_ok=True)
    for size in [180, 192, 512]:
        path = icon_dir / f'icon-{size}.png'
        # Logo files are deterministic source assets; avoid repeated rasterization.
        if not path.exists():
            path.write_bytes(_icon(size))
    manifest = {
        'id': './', 'name': 'БАЗА · Математика 1430', 'short_name': 'БАЗА', 'lang': 'ru',
        'description': 'Математика для ученика и учителя. Практика, учебный маршрут и работы без интернета.',
        'start_url': './', 'scope': './', 'display': 'standalone',
        'background_color': '#edf2ee', 'theme_color': '#243f35',
        'icons': [{'src': f'icons/icon-{size}.png', 'sizes': f'{size}x{size}',
                   'type': 'image/png', 'purpose': 'any maskable'} for size in [192, 512]],
        'categories': ['education'],
    }
    (root / 'manifest.webmanifest').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    refs = set(re.findall(r'<(?:script|link)\b[^>]*\b(?:src|href)="([^"]+)"', html))
    refs = {ref for ref in refs if not ref.startswith('data:')}
    refs.update(['index.html', 'manifest.webmanifest', 'data/NOTICE.txt',
                 'icons/icon-180.png', 'icons/icon-192.png', 'icons/icon-512.png'])

    def entry(name):
        path = root / name
        if not path.is_file() or path.is_symlink() or not path.resolve().is_relative_to(root.resolve()):
            raise ValueError(f'Invalid PWA asset: {name}')
        contents = path.read_bytes()
        return {'url': name, 'bytes': len(contents), 'sha256': hashlib.sha256(contents).hexdigest()}

    core = [entry(name) for name in sorted(refs)]
    assets = {key: entry(value['file']) for key, value in asset_manifest['assets'].items()}
    config = {'core': core, 'assets': list(assets.values()),
              'shared': [assets[key] for key in ['pdf-lib', 'fontkit', 'pdf-font']],
              'grades': {str(grade): [assets[f'class:{grade}']] for grade in range(5, 12)}}
    template = (root / 'src/pwa-worker.js').read_text(encoding='utf-8')
    version = hashlib.sha256((json.dumps(config, sort_keys=True) + template).encode()).hexdigest()[:20]
    config = {'version': version, **config}
    (root / 'service-worker.js').write_text(
        '// Generated by scripts/build.py. Edit src/pwa-worker.js.\nconst PWA_CONFIG = '
        + json.dumps(config, separators=(',', ':')) + ';\n' + template,
        encoding='utf-8', newline='\n')
    return {'version': version, 'coreFiles': len(core), 'coreBytes': sum(asset['bytes'] for asset in core)}
