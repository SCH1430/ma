  function help(q = {}) {
    const authored = explicitHints(q);
    if (authored) return authored;
    const topic = topicIndex.get(q.id);
    const normalize = value => String(value || '').toLowerCase().replace(/ё/g, 'е');
    const prompt = normalize(q.prompt);
    const context = normalize([q.topic, q.topicTitle, q.subject, topic?.title, topic?.subject]
      .filter(x => typeof x === 'string').join(' '));
    if (q.kind === 'open') {
      return {
        hint: 'Сформулируйте, что дано и что нужно обосновать. Отдельный удачный пример обычно не заменяет доказательство общего утверждения.',
        step: 'Выберите правило или определение, связывающее данные с выводом. Для построения опишите шаги и проверьте результат; для опровержения достаточно одного проверенного контрпримера.'
      };
    }
    // The concrete question wins over a broad topic title. Generic arithmetic
    // and equation advice is used only after trying the more specific topic.
    for (const text of [prompt, context]) {
      for (const [pattern, hints, scope] of rules) {
        if (scope !== 'general' && pattern.test(text)) return {hint: hints[0], step: hints[1]};
      }
    }
    for (const [pattern, hints, scope] of rules) {
      if (scope === 'general' && pattern.test(prompt + ' ' + context)) return {hint: hints[0], step: hints[1]};
    }
    return {
      hint: 'Перечислите данные, искомую величину и единицы измерения. Отделите ограничения от числовых сведений.',
      step: 'Изобразите условие схемой или короткой таблицей. Запишите связь между данными и искомым, выполните один шаг и проверьте, не нарушены ли ограничения.'
    };
  }

  return Object.freeze({help});
